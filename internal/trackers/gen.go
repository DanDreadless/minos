//go:build ignore

// Generator for trackers.tsv — tracker domain → company and category, from
// AdGuard's companiesdb (CC BY-SA 4.0; itself built from WhoTracks.me).
// CC BY-SA 4.0 is one-way compatible with GPLv3, so the derived table ships
// inside Minos with attribution (README, NOTICE, the Privacy page). The
// Disconnect and DuckDuckGo Tracker Radar lists are CC BY-NC-SA — not
// usable here.
//
// The source classifies domains as they appear *inside web pages*, so it
// calls google.com, yandex.ru and yahoo.com advertising or analytics, and
// lists Google's and Amazon's infrastructure (1e100.net,
// elasticbeanstalk.com). Blocking those by DNS name would break whole
// services. So the tracking names (T rows) come from Hagezi Pro, a curated
// DNS blocklist (GPLv3) that already avoids that breakage: its rules that
// fall under a company's advertising, analytics or telemetry domain. Only
// those count as tracking and are blocked by "block this company". Run:
//
//	curl -fsSL -o trackers.json  https://raw.githubusercontent.com/AdguardTeam/companiesdb/main/dist/trackers.json
//	curl -fsSL -o companies.json https://raw.githubusercontent.com/AdguardTeam/companiesdb/main/dist/companies.json
//	curl -fsSL -o pro.txt        https://raw.githubusercontent.com/hagezi/dns-blocklists/main/adblock/pro.txt
//	go run gen.go trackers.json companies.json pro.txt trackers.tsv
//
// then commit trackers.tsv.
package main

import (
	"encoding/json"
	"fmt"
	"os"
	"sort"
	"strings"
)

type trackersFile struct {
	TimeUpdated string            `json:"timeUpdated"`
	Categories  map[string]string `json:"categories"`
	Trackers    map[string]struct {
		Name       string `json:"name"`
		CategoryID *int   `json:"categoryId"`
		CompanyID  string `json:"companyId"`
	} `json:"trackers"`
	TrackerDomains map[string]string `json:"trackerDomains"`
}

type companiesFile struct {
	Companies map[string]struct {
		Name string `json:"name"`
	} `json:"companies"`
}

// clean keeps a field to one printable line with no tabs.
func clean(s string) string {
	s = strings.Map(func(r rune) rune {
		if r < 0x20 || r == 0x7f {
			return ' '
		}
		return r
	}, s)
	return strings.TrimSpace(s)
}

func main() {
	if len(os.Args) != 5 {
		fmt.Fprintln(os.Stderr, "usage: go run gen.go trackers.json companies.json pro.txt trackers.tsv")
		os.Exit(2)
	}
	var tf trackersFile
	var cf companiesFile
	for path, v := range map[string]any{os.Args[1]: &tf, os.Args[2]: &cf} {
		raw, err := os.ReadFile(path)
		if err != nil {
			panic(err)
		}
		if err := json.Unmarshal(raw, v); err != nil {
			panic(fmt.Errorf("%s: %w", path, err))
		}
	}
	vetted := map[string]bool{}
	pro, err := os.ReadFile(os.Args[3])
	if err != nil {
		panic(err)
	}
	for line := range strings.SplitSeq(string(pro), "\n") {
		line = strings.TrimSpace(line)
		if strings.HasPrefix(line, "||") && strings.HasSuffix(line, "^") {
			vetted[strings.ToLower(line[2:len(line)-1])] = true
		}
	}
	if len(vetted) < 50000 {
		panic(fmt.Sprintf("pro.txt looks wrong: %d rules", len(vetted)))
	}
	// nearest finds name or its closest parent in set ("" when none).
	nearest := func(set map[string]bool, name string) string {
		for name != "" {
			if set[name] {
				return name
			}
			i := strings.IndexByte(name, '.')
			if i < 0 {
				return ""
			}
			name = name[i+1:]
		}
		return ""
	}

	used := map[string]bool{}
	var domains []string
	for d, tid := range tf.TrackerDomains {
		t, ok := tf.Trackers[tid]
		if !ok || t.CompanyID == "" || strings.ContainsAny(d, " \t/") {
			continue
		}
		if _, ok := cf.Companies[t.CompanyID]; !ok {
			continue
		}
		used[t.CompanyID] = true
		domains = append(domains, d)
	}
	sort.Strings(domains)
	var ids []string
	for id := range used {
		ids = append(ids, id)
	}
	sort.Strings(ids)

	var b strings.Builder
	fmt.Fprintf(&b, "# Tracker domains, companies and categories. Generated by gen.go from AdGuard companiesdb\n")
	fmt.Fprintf(&b, "# (https://github.com/AdguardTeam/companiesdb, built from WhoTracks.me), licensed CC BY-SA 4.0.\n")
	fmt.Fprintf(&b, "# Tracking names (T rows) are Hagezi Pro rules (GPLv3, https://github.com/hagezi/dns-blocklists).\n")
	fmt.Fprintf(&b, "# Source updated %s. Do not edit by hand.\n", tf.TimeUpdated)
	for _, id := range ids {
		fmt.Fprintf(&b, "C\t%s\t%s\n", clean(id), clean(cf.Companies[id].Name))
	}
	category := map[string]string{} // Table domain → category
	company := map[string]string{}
	inTable := map[string]bool{}
	for _, d := range domains {
		t := tf.Trackers[tf.TrackerDomains[d]]
		cat := "unknown"
		if t.CategoryID != nil {
			if c, ok := tf.Categories[fmt.Sprint(*t.CategoryID)]; ok {
				cat = c
			}
		}
		ld := strings.ToLower(clean(d))
		category[ld], company[ld], inTable[ld] = cat, clean(t.CompanyID), true
		fmt.Fprintf(&b, "D\t%s\t%s\t%s\t%s\n", ld, clean(t.CompanyID), clean(cat), clean(t.Name))
	}
	// Tracking names: Hagezi Pro rules under an advertising, analytics or
	// telemetry domain, and such domains Hagezi blocks through a parent.
	tracking := func(cat string) bool {
		switch cat {
		case "advertising", "pornvertising", "site_analytics", "mobile_analytics", "telemetry":
			return true
		}
		return false
	}
	names := map[string]string{} // Tracking name → company
	for r := range vetted {
		if o := nearest(inTable, r); o != "" && tracking(category[o]) {
			names[r] = company[o]
		}
	}
	for d := range inTable {
		if tracking(category[d]) && nearest(vetted, d) != "" {
			names[d] = company[d]
		}
	}
	keys := make([]string, 0, len(names))
	for n := range names {
		keys = append(keys, n)
	}
	sort.Strings(keys)
	for _, n := range keys {
		fmt.Fprintf(&b, "T\t%s\t%s\n", n, names[n])
	}
	if err := os.WriteFile(os.Args[4], []byte(b.String()), 0o644); err != nil {
		panic(err)
	}
	fmt.Printf("%d companies, %d domains, %d tracking names\n", len(ids), len(domains), len(keys))
}
